/// 안 B — 자동 명암으로 부피를 잡고 **특징을 손으로 덧찍는다**.
/// A와 다른 점: 눈이 커지고, 모자 금띠·옷깃·밑단 장식이 생기고,
/// 수염에 단계가 붙고, 보석이 광을 두른다.
final PixelSprite kPilotWizardB = _buildPilotB();

PixelSprite _buildPilotB() {
  final b = SpriteBuilder(_s, _s);
  const cx = 23.0;

  // ── 부피: 어깨를 모자챙보다 넓게 (2-C 규칙) ──
  b.ellipse(cx, 31, 15.0, 6.5); // 어깨
  b.trapezoid(cx, 31, 14.5, 47, 18); // 망토
  b.ellipse(35.5, 34, 4.6, 6.4); // 지팡이 잡은 팔
  b.ellipse(10.5, 34, 4.6, 6.4); // 반대쪽 팔
  b.shade();
  b.outline();

  // 망토 주름 — 자동 명암 위에 손으로 얹는다
  for (final fx in [cx - 8.0, cx + 1.0, cx + 9.0]) {
    for (var y = 35; y <= 45; y++) {
      b.paint(fx, y, fx, y, '2');
    }
  }
  b.paint(cx - 14, 46, cx + 15, 46, '1');
  b.paint(cx - 14, 47, cx + 15, 47, '1');

  // ── 모자 (따로 만들어 덮어야 명암이 안 섞인다) ──
  final hat = SpriteBuilder(_s, _s);
  hat.polygon([
    const Point(cx + 3, 2.0),
    const Point(cx + 8, 20.0),
    const Point(cx - 8, 20.0),
  ]);
  hat.ellipse(cx, 21.0, 12, 2.6); // 챙
  hat.shade();
  hat.outline();
  _overlay(b, hat);

  // 손으로 덧찍기 1 — 모자 금색 띠 + 버클
  b.paint(cx - 6, 17, cx + 8, 17, 'y');
  b.paint(cx - 7, 18, cx + 9, 18, 'x');
  b.paint(cx - 5, 17, cx - 1, 17, 'e');
  b.paint(cx + 3, 17, cx + 4, 17, 'w');
  // 챙 아랫면은 그늘
  b.paint(cx - 11, 22, cx + 11, 22, '1');

  // ── 얼굴 ──
  b.ellipse(cx, 26.5, 7.6, 4.6, ch: 's');
  b.paint(cx - 8, 23, cx + 8, 23, '1'); // 챙 그림자
  // 손으로 덧찍기 2 — 큰 눈 + 눈빛
  for (final ex in [cx - 5, cx + 2]) {
    b.paint(ex, 26, ex + 3, 27, 'k');
    b.paint(ex, 26, ex, 26, 'w');
    b.paint(ex + 2, 27, ex + 3, 27, 'c');
  }
  b.paint(cx - 1, 28, cx + 1, 28, 't'); // 코 그늘

  // ── 수염 — 손으로 단계를 넣는다 ──
  b.ellipse(cx, 32.5, 8.2, 5.6, ch: 'w');
  b.ellipse(cx, 36.0, 5.0, 4.4, ch: 'w');
  b.paint(cx - 8, 29, cx + 8, 30, 'w'); // 콧수염
  b.paint(cx - 8, 29, cx - 3, 29, 'b');
  for (final fx in [cx - 4.0, cx + 1.0, cx + 5.0]) {
    for (var y = 32; y <= 39; y++) {
      b.paint(fx, y, fx, y, 'b');
    }
  }
  b.paint(cx + 4, 33, cx + 8, 35, 'b'); // 오른쪽 그늘

  // ── 옷깃·밑단 금색 장식 (손으로) ──
  b.paint(cx - 11, 31, cx - 7, 31, 'x');
  b.paint(cx + 7, 31, cx + 11, 31, 'x');
  b.paint(cx - 15, 44, cx + 16, 44, 'x');
  b.paint(cx - 12, 44, cx - 2, 44, 'y');

  // ── 지팡이 + 발광 보석 ──
  b.rect(41, 16, 43, 47, ch: 'n');
  b.rect(41, 16, 41, 47, ch: 'u');
  b.rect(43, 16, 43, 47, ch: 'u');
  b.paint(41, 24, 43, 24, 'x');
  b.ellipse(42.5, 34.5, 3.4, 2.4, ch: 's'); // 손
  b.paint(41, 35, 44, 35, 't');
  // 보석 — 바깥 광 → 노란빛 → 백광
  b.ellipse(42.5, 11, 4.6, 4.6, ch: 'x');
  b.ellipse(42.5, 11, 3.6, 3.6, ch: 'y');
  b.ellipse(42.5, 11, 2.6, 2.6, ch: 'e');
  b.ellipse(41.8, 10.2, 1.3, 1.3, ch: 'w');
  b.paint(41, 15, 44, 15, 'x');
  return b.build();
}

/// 다른 스프라이트를 이 스프라이트 위에 덮어쓴다 (투명은 건너뛴다)
void _overlay(SpriteBuilder base, SpriteBuilder top) {
  final rows = top.build().rows;
  for (var y = 0; y < rows.length; y++) {
    for (var x = 0; x < rows[y].length; x++) {
      final ch = rows[y][x];
      if (ch != '.') base.paint(x, y, x, y, ch);
    }
  }
}

